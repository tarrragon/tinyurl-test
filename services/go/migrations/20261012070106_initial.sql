CREATE INDEX "links_id_idx" ON "links" ("id" DESC) WHERE (send_id IS NULL);
-- Create index "links_send_id_idx" to table: "links"
CREATE INDEX "links_send_id_idx" ON "links" ("send_id") WHERE (send_id IS NOT NULL);
-- Create index "links_team_campaign_idx" to table: "links"
CREATE INDEX "links_team_campaign_idx" ON "links" ("team_id", "campaign", "id" DESC) WHERE (send_id IS NULL);
