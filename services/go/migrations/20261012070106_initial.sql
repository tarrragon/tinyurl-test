-- Create "teams" table
CREATE TABLE "teams" (
  "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "name" text NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY ("id"),
  CONSTRAINT "teams_name_key" UNIQUE ("name"),
  CONSTRAINT "teams_name_check" CHECK ((char_length(name) >= 1) AND (char_length(name) <= 100))
);
-- Create "users" table
CREATE TABLE "users" (
  "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "email" text NOT NULL,
  "password_hash" text NOT NULL,
  "role" text NOT NULL,
  "team_id" bigint NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "disabled_at" timestamptz NULL,
  PRIMARY KEY ("id"),
  CONSTRAINT "users_email_key" UNIQUE ("email"),
  CONSTRAINT "users_team_id_fkey" FOREIGN KEY ("team_id") REFERENCES "teams" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT "users_email_check" CHECK ((email = lower(email)) AND (char_length(email) <= 254)),
  CONSTRAINT "users_role_check" CHECK (role = ANY (ARRAY['marketing'::text, 'marketing_lead'::text, 'engineer'::text, 'admin'::text])),
  CONSTRAINT "users_team_check" CHECK ((role <> ALL (ARRAY['marketing'::text, 'marketing_lead'::text])) OR (team_id IS NOT NULL))
);
-- Create index "users_team_id_idx" to table: "users"
CREATE INDEX "users_team_id_idx" ON "users" ("team_id");
-- Create "api_keys" table
CREATE TABLE "api_keys" (
  "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "team_id" bigint NOT NULL,
  "name" text NOT NULL,
  "key_hash" bytea NOT NULL,
  "created_by" bigint NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "revoked_at" timestamptz NULL,
  PRIMARY KEY ("id"),
  CONSTRAINT "api_keys_key_hash_key" UNIQUE ("key_hash"),
  CONSTRAINT "api_keys_created_by_fkey" FOREIGN KEY ("created_by") REFERENCES "users" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT "api_keys_team_id_fkey" FOREIGN KEY ("team_id") REFERENCES "teams" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT "api_keys_name_check" CHECK ((char_length(name) >= 1) AND (char_length(name) <= 50))
);
-- Create "sends" table
CREATE TABLE "sends" (
  "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "team_id" bigint NOT NULL,
  "campaign" text NOT NULL,
  "channel" text NOT NULL,
  "original_url" text NOT NULL,
  "created_by" bigint NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY ("id"),
  CONSTRAINT "sends_created_by_fkey" FOREIGN KEY ("created_by") REFERENCES "users" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT "sends_team_id_fkey" FOREIGN KEY ("team_id") REFERENCES "teams" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT "sends_campaign_check" CHECK ((char_length(campaign) >= 1) AND (char_length(campaign) <= 100)),
  CONSTRAINT "sends_channel_check" CHECK (channel = ANY (ARRAY['sms'::text, 'email'::text, 'ad'::text])),
  CONSTRAINT "sends_url_check" CHECK (char_length(original_url) <= 2048)
);
-- Create index "sends_created_by_idx" to table: "sends"
CREATE INDEX "sends_created_by_idx" ON "sends" ("created_by", "id" DESC);
-- Create index "sends_team_campaign_idx" to table: "sends"
CREATE INDEX "sends_team_campaign_idx" ON "sends" ("team_id", "campaign");
-- Create "links" table
CREATE TABLE "links" (
  "id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
  "code" text NOT NULL,
  "send_id" bigint NULL,
  "original_url" text NULL,
  "channel" text NULL,
  "campaign" text NULL,
  "created_by" bigint NOT NULL,
  "team_id" bigint NULL,
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "expires_at" timestamptz NOT NULL,
  "disabled_at" timestamptz NULL,
  PRIMARY KEY ("id"),
  CONSTRAINT "links_code_key" UNIQUE ("code"),
  CONSTRAINT "links_created_by_fkey" FOREIGN KEY ("created_by") REFERENCES "users" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT "links_send_id_fkey" FOREIGN KEY ("send_id") REFERENCES "sends" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT "links_team_id_fkey" FOREIGN KEY ("team_id") REFERENCES "teams" ("id") ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT "links_campaign_check" CHECK ((char_length(campaign) >= 1) AND (char_length(campaign) <= 100)),
  CONSTRAINT "links_channel_check" CHECK (channel = ANY (ARRAY['sms'::text, 'email'::text, 'ad'::text])),
  CONSTRAINT "links_code_check" CHECK (code ~ '^[0-9A-Za-z]{6,7}$'::text),
  CONSTRAINT "links_send_fields_check" CHECK (((send_id IS NULL) AND (original_url IS NOT NULL) AND (channel IS NOT NULL) AND (campaign IS NOT NULL)) OR ((send_id IS NOT NULL) AND (channel IS NULL) AND (campaign IS NULL))),
  CONSTRAINT "links_url_check" CHECK (char_length(original_url) <= 2048)
);
-- Create index "links_campaign_id_idx" to table: "links"
CREATE INDEX "links_campaign_id_idx" ON "links" ("campaign", "id" DESC) WHERE (send_id IS NULL);
